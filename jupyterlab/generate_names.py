"""Writes src/names.ts, the names the gmacs highlighter colours as built in.

Both spellings of every renamed GLSL name come from the dialect's own table,
which Sara keeps at sara-godot/core/custom-shader/gmacs_names.json in its own
repository. Its path is the one argument:

    python3 generate_names.py ../sara/sara-godot/core/custom-shader/gmacs_names.json

so a name the dialect gains is coloured after the next run. The GLSL functions
gmacs keeps under their own name, and the few names the pixel function wrapper
adds, are listed here.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# GLSL built-in functions gmacs spells as GLSL does, plus its two range forms.
STD_FUNCS = """
abs acos all any asin atan bool ceil clamp cos cosh cross degrees determinant
distance dot equal exp exp2 faceforward float floor fma fract int inverse
inversesqrt isinf isnan length log log2 max min mix mod normalize not_equal pow
radians range range_inclusive reflect refract round sign sin sinh smoothstep
sqrt step tan tanh transpose trunc uint
""".split()

# What the pixel function wrapper defines around a student's cell.
WRAPPER_FUNCS = ["src", "luminance"]
WRAPPER_VARS = ["pixel"]


def as_set(name, values):
    return f"export const {name} = new Set({json.dumps(sorted(set(values)))});\n"


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: python3 generate_names.py <path to Sara's gmacs_names.json>")
    table = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    functions = list(table["functions"]) + list(table["functions"].values())
    variables = list(table["variables"]) + list(table["variables"].values()) + WRAPPER_VARS
    out = HERE / "src" / "names.ts"
    out.write_text(
        "// Generated by generate_names.py from gmacs_names.json. Do not edit by hand.\n"
        + as_set("BUILTIN_FUNCS", functions)
        + as_set("BUILTIN_VARS", variables)
        + as_set("STD_FUNCS", STD_FUNCS + WRAPPER_FUNCS),
        encoding="utf-8",
    )
    print(out, len(functions), "renamed functions,", len(variables), "variables")


if __name__ == "__main__":
    main()
